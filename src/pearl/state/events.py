_EVENT_REGISTRY = {ToolCallEvent.event_type: ToolCallEvent, ObservationEvent.event_type: ObservationEvent, PlanEvent.event_type: PlanEvent, PredictionEvent.event_type: PredictionEvent, KnowledgeRequestEvent.event_type: KnowledgeRequestEvent, KnowledgeResponseEvent.event_type: KnowledgeResponseEvent, AnomalyMatchEvent.event_type: AnomalyMatchEvent, RevisedPlanEvent.event_type: RevisedPlanEvent, WorkingPlanDeclaredEvent.event_type: WorkingPlanDeclaredEvent, PeerReviewDispositionEvent.event_type: PeerReviewDispositionEvent}

def known_event_types() -> frozenset[str]:
    """Return every registered ``event_type`` string.

    Consumers that classify serialized events use this instead of copying the
    vocabulary, so an unrecognized type can be reported rather than silently
    dropped when the registry grows.
    """
    return frozenset(_EVENT_REGISTRY)

def replay_events(events: list[Event], target_ctx=None) -> None:
    """Re-publish *events* into *target_ctx* (default: current ToolContext).

    Use to reconstruct blackboard state from a saved log or to run a
    deterministic test fixture against subscribers.  Event identity
    (event_id, timestamp) is preserved — replay does not mint new ids.
    """
    if target_ctx is None:
        raise ValueError('An explicit target blackboard is required')
    for event in events:
        target_ctx.publish(event)
