from __future__ import annotations
import math
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from typing import Any, ClassVar
from uuid import uuid4

def _now_iso() -> str:
    """Return current UTC time in ISO-8601 format."""
    return datetime.now(timezone.utc).isoformat()

@dataclass
class Event:
    """Base class for all blackboard events."""
    event_type: ClassVar[str] = 'event'
    event_id: str = field(default_factory=lambda: uuid4().hex)
    timestamp: str = field(default_factory=_now_iso)
    source_agent: str | None = None
    trace_sequence: int = 0

    def to_dict(self) -> dict[str, Any]:
        """Serialize to JSON-compatible dict."""
        d = asdict(self)
        if d.get('prediction_review') is None:
            d.pop('prediction_review', None)
        if self.trace_sequence == 0:
            for name in ('trace_sequence', 'tool_call_id', 'plan_id', 'revision_id', 'trigger_detection_id', 'corrective_action_type', 'executed', 'result_observation_ids', 'state_change_verified', 'canonical_operations', 'canonicalization_version', 'execution_approved', 'tool_call_ids', 'parent_plan_id'):
                if name == 'plan_id' and (not isinstance(self, ToolCallEvent)):
                    continue
                if name == 'parent_plan_id' and isinstance(self, RevisedPlanEvent):
                    continue
                d.pop(name, None)
        d['event_type'] = type(self).event_type
        return d

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> Event:
        """Deserialize from dict, routing to correct subclass by event_type."""
        event_type = d.get('event_type', 'event')
        target_cls = _EVENT_REGISTRY.get(event_type, Event)
        kwargs = {k: v for k, v in d.items() if k != 'event_type'}
        return target_cls(**kwargs)

@dataclass
class ToolCallEvent(Event):
    """Record of a tool call made by an agent."""
    event_type: ClassVar[str] = 'tool_call'
    tool_name: str = ''
    params: dict[str, Any] = field(default_factory=dict)
    result: Any = None
    state_delta: dict[str, Any] = field(default_factory=dict)
    tool_call_id: str = ''
    plan_id: str = ''
    revision_id: str = ''
    trigger_detection_id: str = ''
    corrective_action_type: str = ''
    executed: bool | None = None
    result_observation_ids: list[str] = field(default_factory=list)
    state_change_verified: bool | None = None

@dataclass
class ObservationEvent(Event):
    """Observation from the environment (camera, state, etc.)."""
    event_type: ClassVar[str] = 'observation'
    observation_type: str = ''
    payload: dict[str, Any] = field(default_factory=dict)

def _validate_plan_execution_lineage(execution_approved: object, tool_call_ids: object) -> None:
    if type(execution_approved) is not bool:
        raise TypeError('execution_approved must be boolean')
    if not isinstance(tool_call_ids, list) or any((not isinstance(item, str) or not item.strip() for item in tool_call_ids)):
        raise ValueError('tool_call_ids must be a list of non-empty strings')
    if len(set(tool_call_ids)) != len(tool_call_ids):
        raise ValueError('tool_call_ids must not contain duplicates')
    if tool_call_ids and (not execution_approved):
        raise ValueError('tool_call_ids require execution_approved')

@dataclass
class PlanEvent(Event):
    """Plan generated by a reasoning agent."""
    event_type: ClassVar[str] = 'plan'
    experiment_id: str = ''
    plan_id: str = ''
    parent_plan_id: str = ''
    steps: list[dict[str, Any]] = field(default_factory=list)
    rationale: str = ''
    revision_id: str = ''
    trigger_detection_id: str = ''
    canonical_operations: list[dict[str, Any]] = field(default_factory=list)
    canonicalization_version: str = ''
    execution_approved: bool = False
    tool_call_ids: list[str] = field(default_factory=list)
    prediction_review: dict[str, Any] | None = None

    def __post_init__(self) -> None:
        _validate_plan_execution_lineage(self.execution_approved, self.tool_call_ids)

